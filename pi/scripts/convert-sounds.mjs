// Converts the Playtune scores in ../esp/src/sounds/Sounds.h into
// src/sounds/scores.ts. Only needed again if that file changes.
//
//   node scripts/convert-sounds.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));

const src = readFileSync(here('../../esp/src/sounds/Sounds.h'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');

let out = `// GENERATED by scripts/convert-sounds.mjs from esp/src/sounds/Sounds.h.
// Playtune score format, see SoundPlayer.ts.

`;

for (const [, name, body] of src.matchAll(/const\s+byte\s+PROGMEM\s+(\w+)\[\]\s*=\s*\{([^}]*)\}/g)) {
    const bytes = body.split(',').map((s) => s.trim()).filter(Boolean).map(Number);
    if (bytes.some((b) => !Number.isInteger(b) || b < 0 || b > 255))
        throw new Error(`${name}: not a byte array`);
    const lines = [];
    for (let i = 0; i < bytes.length; i += 20)
        lines.push('    ' + bytes.slice(i, i + 20).join(', ') + ',');
    out += `export const ${name} = new Uint8Array([\n${lines.join('\n')}\n]);\n\n`;
}

writeFileSync(here('../src/sounds/scores.ts'), out.trimEnd() + '\n');
