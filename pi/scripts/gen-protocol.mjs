// Generates src/protocol/map.ts from the C headers in ../protocol, so the Pi
// always uses the same IDs and message types as the Mega.
//
//   node scripts/gen-protocol.mjs          write src/protocol/map.ts
//   node scripts/gen-protocol.mjs --check  fail if it is out of date
//
// Runs automatically before every build.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const OUT = here('../src/protocol/map.ts');

// C enum name -> exported object name, and the prefix to strip from each entry
const ENUMS = {
    SwitchId: ['Switch', 'SW_'],
    LampId: ['Lamp', 'LAMP_'],
    CoilId: ['Coil', 'COIL_'],
    MsgType: ['Msg', 'MSG_'],
};

const NUMBER = /^(0x[0-9a-fA-F]+|\d+)$/;

function stripComments(src) {
    return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

function parse(file) {
    const src = stripComments(readFileSync(here(`../../protocol/${file}`), 'utf8'));
    const enums = [];
    for (const [, name, body] of src.matchAll(/enum\s+(\w+)\s*:\s*\w+\s*\{([^}]*)\}/g)) {
        const entries = body
            .split(',')
            .map((e) => e.trim())
            .filter(Boolean)
            .map((e) => e.split('=').map((s) => s.trim()));
        for (const [key, value] of entries) {
            if (!NUMBER.test(value ?? ''))
                throw new Error(`${file}: ${name}.${key} needs an explicit number`);
        }
        enums.push({ name, entries });
    }
    // Only literal numbers. Derived ones (SWITCH_BYTES etc.) are computed in index.ts.
    const consts = [...src.matchAll(/const\s+u?int\d+_t\s+(\w+)\s*=\s*([^;]+);/g)]
        .map(([, key, value]) => [key, value.trim()])
        .filter(([, value]) => NUMBER.test(value));
    return { enums, consts };
}

let out = `// GENERATED by scripts/gen-protocol.mjs from protocol/MachineMap.h and
// protocol/Protocol.h. Do not edit: change the headers and rebuild.

`;

for (const file of ['MachineMap.h', 'Protocol.h']) {
    const { enums, consts } = parse(file);
    for (const [key, value] of consts)
        out += `export const ${key} = ${value};\n`;
    out += '\n';
    for (const { name, entries } of enums) {
        const [obj, prefix] = ENUMS[name] ?? [name, ''];
        out += `export const ${obj} = {\n`;
        for (const [key, value] of entries)
            out += `    ${key.startsWith(prefix) ? key.slice(prefix.length) : key}: ${value},\n`;
        out += `} as const;\n`;
        out += `export type ${name} = (typeof ${obj})[keyof typeof ${obj}];\n\n`;
    }
}
out = out.trimEnd() + '\n';

if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = readFileSync(OUT, 'utf8');
    } catch {}
    if (current !== out) {
        console.error('src/protocol/map.ts is out of date. Run: node scripts/gen-protocol.mjs');
        process.exit(1);
    }
} else {
    writeFileSync(OUT, out);
}
